def validate_bank() -> None:
    ids = [q["id"] for q in QUESTIONS]
    if len(ids) != 100 or len(set(ids)) != 100:
        raise SystemExit(f"题量或题号重复: {len(ids)} unique={len(set(ids))}")
    missing = [f"Q{i:03d}" for i in range(1, 101) if f"Q{i:03d}" not in ids]
    if missing:
        raise SystemExit(f"缺题号: {missing}")
    typ = {}
    split = {}
    for q in QUESTIONS:
        typ[q["type"]] = typ.get(q["type"], 0) + 1
        split[q["split"]] = split.get(q["split"], 0) + 1
    if typ.get("single_hop") != 60 or typ.get("multi_hop") != 25 or typ.get("refusal") != 15:
        raise SystemExit(f"类型统计不符: {typ}")
    if split.get("dev") != 70 or split.get("test") != 30:
        raise SystemExit(f"拆分不符: {split}")
    by_id = {q["id"]: q for q in QUESTIONS}
    if by_id["Q041"]["split"] != "dev":
        raise SystemExit("Q041 必须在开发集")
    if by_id["Q042"]["split"] != "test":
        raise SystemExit("Q042 必须在测试集")
    if by_id["Q039"]["type"] == "refusal" or by_id["Q039"]["should_refuse"]:
        raise SystemExit("Q039 不得进入拒答集")
    if by_id["Q025"]["type"] != "multi_hop":
        raise SystemExit("Q025 应为多跳")
    # 簇不得跨 split
    cluster_split = {}
    for q in QUESTIONS:
        if q["cluster"] in cluster_split and cluster_split[q["cluster"]] != q["split"]:
            raise SystemExit(f"簇 {q['cluster']} 跨越 dev/test")
        cluster_split[q["cluster"]] = q["split"]
    # 拒答不得带正式金标跨度
    for q in QUESTIONS:
        if q["should_refuse"] and q["span_specs"]:
            raise SystemExit(f"{q['id']} 拒答不应标注正式条款跨度")
        if q["type"] == "refusal" and not q["should_refuse"]:
            raise SystemExit(f"{q['id']} 拒答类型未标记 should_refuse")


if __name__ == "__main__":
    validate_bank()
    print("question bank ok: 100 questions")
